import { chromium } from "playwright";

const base = process.env.PLAY_BASE ?? "http://localhost:3101";
const out = process.env.SHOTS ?? "shots";
const width = Number(process.env.W ?? 390);
const setup = process.env.SETUP ?? "mix";
const game = process.env.GAME ?? "daily";

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width, height: width < 600 ? 844 : 900 } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const shot = (n) => page.screenshot({ path: `${out}/${width}-${setup}-${n}.png`, fullPage: false });
await page.goto(`${base}/play`);
await page.getByTestId("nickname").fill("Tester");
await page.getByTestId("nickname-go").click();
await page.getByTestId("create").waitFor();
await page.getByTestId(`setup-${setup}`).click();
if (setup === "single") await page.getByTestId(`game-${game}`).click();
await shot("setup");
await page.getByTestId("create").click();
await page.getByTestId("room").waitFor().catch(async (e) => { await shot("fail"); console.log(await page.locator("[role=alert]").allInnerTexts()); throw e; });
await page.getByTestId("ready").click();
const fill = page.getByTestId("fill-bots");
if (await fill.isVisible().catch(() => false)) await fill.click();
await page.getByTestId("next-start-count").waitFor({ timeout: 30000 });
await shot("waiting");
await page.getByTestId("hud").waitFor({ timeout: 40000 });
await page.getByTestId("choice").first().or(page.getByTestId("tiles")).first().waitFor({ timeout: 20000 });
await shot("round");
const choice = page.getByTestId("choice").nth(1);
if (await choice.isVisible().catch(() => false)) await choice.click();
await page.getByTestId("verdict").or(page.getByTestId("reveal")).first().waitFor({ timeout: 30000 });
await shot("reveal");
await page.getByTestId("results").waitFor({ timeout: 180000 });
await shot("results");
await page.getByTestId("next-game").waitFor();
console.log(JSON.stringify({ width, setup, errors, next: await page.getByTestId("next-game").innerText(), overflow: await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth) }));
await browser.close();
